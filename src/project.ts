import * as fs from 'node:fs';
import * as path from 'node:path';
import { transpile } from './index.js';

const CONFIG_NAME = 'polishts.config.json';
const OUTPUT_MARKER = '.polishts-generated-project';
const OUTPUT_MARKER_CONTENT = 'Generated by PolishTS project mode. This directory is safe to replace.\n';
const DEFAULT_INCLUDE = ['src'];
const DEFAULT_EXCLUDE = ['.git', 'node_modules', 'dist', 'coverage', '.next', 'build', 'pltsxGenerated'];

interface ProjectConfig {
  include?: string[];
  exclude?: string[];
  outDir?: string;
}

interface ResolvedProjectConfig {
  include: string[];
  exclude: string[];
  outDir: string;
}

interface ProjectFile {
  absolutePath: string;
  projectRelativePath: string;
  kind: 'polish' | 'copy';
}

export interface ProjectTranslationResult {
  sourceFiles: number;
  copiedFiles: number;
  outputDirectory: string;
}

function isInside(parent: string, candidate: string): boolean {
  const relative = path.relative(parent, candidate);
  return relative === '' || (!relative.startsWith(`..${path.sep}`) && relative !== '..' && !path.isAbsolute(relative));
}

function normalizeRelativePath(value: string): string {
  return value.split(path.sep).join('/').replace(/^\.\//, '').replace(/\/$/, '');
}

function validateStringArray(value: unknown, field: string): string[] | undefined {
  if (value === undefined) return undefined;
  if (!Array.isArray(value) || value.some((item) => typeof item !== 'string' || item.length === 0)) {
    throw new Error(`invalid ${CONFIG_NAME}: "${field}" must be an array of non-empty paths`);
  }
  return value;
}

function resolveProjectConfig(projectRoot: string): ResolvedProjectConfig {
  const configPath = path.join(projectRoot, CONFIG_NAME);
  let config: ProjectConfig = {};

  if (fs.existsSync(configPath)) {
    try {
      const parsed: unknown = JSON.parse(fs.readFileSync(configPath, 'utf8'));
      if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
        throw new Error('the config root must be an object');
      }
      config = parsed as ProjectConfig;
    } catch (error) {
      throw new Error(`cannot read ${CONFIG_NAME}: ${(error as Error).message}`);
    }
  }

  const include = validateStringArray(config.include, 'include') ?? DEFAULT_INCLUDE;
  const exclude = validateStringArray(config.exclude, 'exclude') ?? [];
  const outDir = config.outDir ?? 'pltsxGenerated';
  if (typeof outDir !== 'string' || outDir.length === 0) {
    throw new Error(`invalid ${CONFIG_NAME}: "outDir" must be a non-empty path`);
  }

  for (const item of [...include, ...exclude, outDir]) {
    if (path.isAbsolute(item)) throw new Error(`${CONFIG_NAME} paths must be relative to the project directory: ${item}`);
    if (item.split(/[\\/]/).includes('..')) throw new Error(`${CONFIG_NAME} paths cannot use "..": ${item}`);
  }

  return { include, exclude, outDir };
}

function collectProjectFiles(projectRoot: string, config: ResolvedProjectConfig, outputDirectory: string): ProjectFile[] {
  const files = new Map<string, ProjectFile>();
  const excludedPaths = config.exclude.map(normalizeRelativePath);
  const ignoredDirectoryNames = new Set(DEFAULT_EXCLUDE);

  function isExcluded(absolutePath: string): boolean {
    if (isInside(outputDirectory, absolutePath)) return true;
    const relative = normalizeRelativePath(path.relative(projectRoot, absolutePath));
    if (!relative) return false;
    if (relative.split('/').some((part) => ignoredDirectoryNames.has(part))) return true;
    return excludedPaths.some((excluded) => relative === excluded || relative.startsWith(`${excluded}/`));
  }

  function addFile(absolutePath: string): void {
    if (isExcluded(absolutePath)) return;
    const projectRelativePath = normalizeRelativePath(path.relative(projectRoot, absolutePath));
    const extension = path.extname(absolutePath).toLowerCase();
    files.set(projectRelativePath, {
      absolutePath,
      projectRelativePath,
      kind: extension === '.plts' || extension === '.pltsx' ? 'polish' : 'copy',
    });
  }

  function walk(directory: string): void {
    if (isExcluded(directory)) return;
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const absolutePath = path.join(directory, entry.name);
      if (isExcluded(absolutePath) || entry.isSymbolicLink()) continue;
      if (entry.isDirectory()) walk(absolutePath);
      else if (entry.isFile()) addFile(absolutePath);
    }
  }

  for (const includePath of config.include) {
    const absolutePath = path.resolve(projectRoot, includePath);
    if (!isInside(projectRoot, absolutePath)) throw new Error(`input path must stay inside the project: ${includePath}`);
    if (!fs.existsSync(absolutePath)) throw new Error(`project input path not found: ${includePath}`);
    const stat = fs.lstatSync(absolutePath);
    if (stat.isSymbolicLink()) continue;
    if (stat.isDirectory()) walk(absolutePath);
    else if (stat.isFile()) addFile(absolutePath);
  }

  return [...files.values()].sort((a, b) => a.projectRelativePath < b.projectRelativePath ? -1 : a.projectRelativePath > b.projectRelativePath ? 1 : 0);
}

function prepareOutputDirectory(outputDirectory: string): void {
  if (fs.existsSync(outputDirectory)) {
    const stat = fs.lstatSync(outputDirectory);
    if (stat.isSymbolicLink() || !stat.isDirectory()) {
      throw new Error(`project output path must be a regular directory: ${outputDirectory}`);
    }
    const entries = fs.readdirSync(outputDirectory);
    const markerPath = path.join(outputDirectory, OUTPUT_MARKER);
    if (entries.length > 0 && (!fs.existsSync(markerPath) || fs.readFileSync(markerPath, 'utf8') !== OUTPUT_MARKER_CONTENT)) {
      throw new Error(`refusing to replace non-empty output directory without a PolishTS marker: ${outputDirectory}`);
    }
    fs.rmSync(outputDirectory, { recursive: true, force: true });
  }

  fs.mkdirSync(outputDirectory, { recursive: true });
  fs.writeFileSync(path.join(outputDirectory, OUTPUT_MARKER), OUTPUT_MARKER_CONTENT, 'utf8');
}

function rejectSymlinkedOutputPath(projectRoot: string, outputDirectory: string): void {
  let currentPath = projectRoot;
  const relativePath = path.relative(projectRoot, outputDirectory);
  for (const part of relativePath.split(path.sep).filter(Boolean)) {
    currentPath = path.join(currentPath, part);
    if (fs.existsSync(currentPath) && fs.lstatSync(currentPath).isSymbolicLink()) {
      throw new Error(`project output path cannot pass through a symbolic link: ${currentPath}`);
    }
  }
}

export function translateProject(projectPath = process.cwd()): ProjectTranslationResult {
  const projectRoot = path.resolve(projectPath);
  const config = resolveProjectConfig(projectRoot);
  const outputDirectory = path.resolve(projectRoot, config.outDir);
  if (!isInside(projectRoot, outputDirectory) || outputDirectory === projectRoot) {
    throw new Error('project "outDir" must be a directory inside the project');
  }
  rejectSymlinkedOutputPath(projectRoot, outputDirectory);

  for (const includePath of config.include) {
    const inputPath = path.resolve(projectRoot, includePath);
    if (isInside(outputDirectory, inputPath)) {
      throw new Error(`project output directory cannot contain an input path: ${includePath}`);
    }
  }

  const files = collectProjectFiles(projectRoot, config, outputDirectory);
  const polishFiles = files.filter((file) => file.kind === 'polish');
  if (polishFiles.length === 0) throw new Error('no .plts or .pltsx source files found in the project inputs');

  const generated = new Map<string, string>();
  for (const file of polishFiles) {
    const input = fs.readFileSync(file.absolutePath, 'utf8');
    const extension = path.extname(file.projectRelativePath).toLowerCase();
    const outputExtension = extension === '.pltsx' ? '.tsx' : '.ts';
    const outputRelativePath = file.projectRelativePath.slice(0, -extension.length) + outputExtension;
    try {
      generated.set(outputRelativePath, transpile(input, { jsx: extension === '.pltsx' }));
    } catch (error) {
      const location = error && typeof error === 'object' && 'location' in error
        ? (error.location as { line?: number; column?: number } | undefined)
        : undefined;
      const suffix = location ? ` (line ${location.line}, column ${location.column})` : '';
      throw new Error(`${file.projectRelativePath}: ${(error as Error).message}${suffix}`);
    }
  }

  const copiedFiles = files.filter((file) => file.kind === 'copy' && !generated.has(file.projectRelativePath));
  prepareOutputDirectory(outputDirectory);

  for (const [relativePath, contents] of generated) {
    const destination = path.join(outputDirectory, relativePath);
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.writeFileSync(destination, contents, 'utf8');
  }
  for (const file of copiedFiles) {
    const destination = path.join(outputDirectory, file.projectRelativePath);
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.copyFileSync(file.absolutePath, destination);
  }

  return {
    sourceFiles: polishFiles.length,
    copiedFiles: copiedFiles.length,
    outputDirectory,
  };
}
